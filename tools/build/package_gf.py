#!/usr/bin/env python3
"""Build the verified pak-only runtime archive.

Run tools/build/build_gf.sh first. No live game files are read or changed.
The runtime archive mirrors SWZeroCompany, with containers, manager metadata,
documentation and hashes inside Content/Paks/~mods/DenDesigner.
This verifies packaging integrity; it does not certify full in-game acceptance.
"""
import argparse
import hashlib
import re
import json
from pathlib import Path
import zipfile

from gf_build_info import ROOT, PAKS, CONTAINERS, verify, require

PACKAGE_ROOT = "Content/Paks/~mods/DenDesigner"


def runtime_metadata(root, version):
    files = {name: (root / "distribution/pak" / name).read_bytes()
             for name in ("modinfo.json", "zcom-mod.json")}
    info, manifest = (json.loads(files[name]) for name in ("modinfo.json", "zcom-mod.json"))
    require(isinstance(info, dict) and isinstance(manifest, dict), "Expected metadata objects")
    for key in ("version", "author", "description"):
        require(isinstance(info.get(key), str) and info[key].strip()
                and info[key] == manifest.get(key), "Mod metadata differs: " + key)
    require(info["version"] == version, "Mod metadata version differs from the verified runtime")
    require(info.get("title") == manifest.get("name") == "Den Designer", "Mod metadata name differs")
    require(type(manifest.get("schemaVersion")) is int and manifest["schemaVersion"] == 1
            and manifest.get("id") == "community.den-designer", "Unexpected mod-manager identity")
    requirements = manifest.get("requires", {})
    require(manifest.get("type") == ["iostore"] and isinstance(requirements, dict)
            and requirements.get("ue4ss") is False,
            "Runtime metadata must describe a standalone IoStore mod")
    game = manifest.get("game", {})
    require(isinstance(game, dict) and game.get("appId") == 2075800, "Wrong target game")
    builds = game.get("testedBuilds", [])
    require(isinstance(builds, list) and all(isinstance(v, str) and re.fullmatch(r"[0-9]+", v) for v in builds)
            and len(builds) == len(set(builds)), "Invalid tested game builds")
    return files


def digest(data):
    return hashlib.sha256(data).hexdigest()


def archive(path, files, metadata, manifest_name="manifest.json"):
    require(all(isinstance(data, bytes) for data in files.values()), "Archive inputs must be bytes")
    require(manifest_name not in files, "Manifest is generated by the packager")
    manifest = dict(metadata, files={name: {"sha256": digest(data), "bytes": len(data)}
                                    for name, data in sorted(files.items())})
    payloads = dict(files, **{manifest_name: (json.dumps(manifest, indent=2) + "\n").encode()})
    for name in payloads:
        require(not name.startswith("/") and "\\" not in name and ":" not in name
                and all(p not in ("", ".", "..") for p in name.split("/")), "Invalid archive path")
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists():
        with zipfile.ZipFile(path) as existing:
            require(len(existing.namelist()) == len(payloads) and set(existing.namelist()) == set(payloads)
                    and all(existing.read(name) == data for name, data in payloads.items()),
                    path.name + " already exists with different content; use a new version")
    else:
        temporary = path.with_suffix(".zip.tmp")
        require(not temporary.exists(), "Previous package temporary file exists: " + str(temporary))
        try:
            with zipfile.ZipFile(temporary, "x", compression=zipfile.ZIP_DEFLATED) as output:
                for name, data in sorted(payloads.items()):
                    info = zipfile.ZipInfo(name, date_time=(2026, 1, 1, 0, 0, 0))
                    info.compress_type = zipfile.ZIP_DEFLATED
                    info.create_system = 3
                    info.external_attr = 0o100644 << 16
                    output.writestr(info, data, compresslevel=9)
            temporary.rename(path)
        finally:
            if temporary.exists():
                temporary.unlink()
    with zipfile.ZipFile(path) as output:
        require(output.testzip() is None and len(output.namelist()) == len(payloads)
                and set(output.namelist()) == set(payloads), "Archive inventory/CRC failed")
        for name, data in payloads.items():
            require(output.read(name) == data, "Archive bytes differ: " + name)
    checksum = digest(path.read_bytes())
    path.with_suffix(".zip.sha256").write_text(checksum + "  " + path.name + "\n")
    return {"archive": str(path), "sha256": checksum, "files": len(payloads), "bytes": path.stat().st_size}


def require_cooked(root, build):
    evidence = root / 'dist/verification/community/cooked-runtime/report.json'
    require(evidence.is_file(), 'Run tools/build/verify_cooked_runtime.py before packaging: cooked script verification is missing')
    report = json.loads(evidence.read_text())
    require(report.get('version') == build['version'] and report.get('containers') == build['containers']
            and report.get('parsed_packages') == build['cooked_assets'] and report.get('errors') == 0
            and report.get('script_data') is True,
            'Cooked script verification is stale or failed; rerun tools/build/verify_cooked_runtime.py')


def package(root=ROOT):
    build = verify(root)
    require_cooked(root, build)
    require(not build["prototype"], "A feasibility-prototype build is not the editor package")
    version = build["version"]
    preview = "-preview." in version
    require(preview or re.fullmatch(r"\d+\.\d+\.\d+", version), "Expected a stable or preview version")
    metadata = runtime_metadata(root, version)
    files = {name: (root / PAKS / name).read_bytes() for name in CONTAINERS}
    files.update({name: (root / "distribution/pak" / name).read_bytes()
                  for name in ("README.md", "CREDITS.md")})
    files.update(metadata)
    files["LICENSE"] = (root / "LICENSE").read_bytes()
    # Keep every runtime file in the component folder, including integrity records.
    # The ZIP can be extracted into SWZeroCompany; metadata stays beside its payload.
    files = {f"{PACKAGE_ROOT}/{name}": data for name, data in files.items()}
    runtime = archive(root / "dist/packages" / f"DenDesigner-Pak-{version}.zip", files,
                      {"format": 1, "product": "Den Designer", "version": version,
                       "kind": "pak_runtime", "preview": preview, "verification_scope": "build_and_package",
                       "entry_point": build["entry_point"], "cooked_assets": build["cooked_assets"]},
                      manifest_name=f"{PACKAGE_ROOT}/manifest.json")
    return {"runtime": runtime}


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.parse_args()
    try:
        print(json.dumps(package(), indent=2))
    except (ValueError, OSError, KeyError, TypeError, zipfile.BadZipFile) as exc:
        raise SystemExit("Packaging stopped: " + str(exc))
