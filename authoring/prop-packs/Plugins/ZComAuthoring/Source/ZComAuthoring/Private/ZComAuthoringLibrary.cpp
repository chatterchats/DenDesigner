using FJson = TSharedPtr<FJsonObject>;
using FJsonArray = TArray<TSharedPtr<FJsonValue>>;

struct FReport
{
	bool bOk = true;
	TArray<FString> Messages;

	void Error(const FString& Message) { bOk = false; Messages.Add(TEXT("error: ") + Message); }
	void Warn(const FString& Message) { Messages.Add(TEXT("warning: ") + Message); }
	void Info(const FString& Message) { Messages.Add(Message); }
};

FString ValueToString(const TSharedPtr<FJsonValue>& Value)
{
	switch (Value.IsValid() ? Value->Type : EJson::Null)
	{
	case EJson::String:
		return Value->AsString();
	case EJson::Boolean:
		return Value->AsBool() ? TEXT("true") : TEXT("false");
	case EJson::Number:
	{
		const double Number = Value->AsNumber();
		return Number == FMath::FloorToDouble(Number) && FMath::Abs(Number) < 1e15
			? FString::Printf(TEXT("%lld"), static_cast<int64>(Number))
			: FString::SanitizeFloat(Number);
	}
	default:
		return FString();
	}
}

FString StringField(const FJson& Object, const TCHAR* Name, const FString& Default = FString())
{
	FString Value;
	return Object.IsValid() && Object->TryGetStringField(Name, Value) ? Value : Default;
}

const FJsonArray& ArrayField(const FJson& Object, const TCHAR* Name)
{
	static const FJsonArray Empty;
	const FJsonArray* Array = nullptr;
	return Object.IsValid() && Object->TryGetArrayField(Name, Array) ? *Array : Empty;
}

FJson ObjectField(const FJson& Object, const TCHAR* Name)
{
	const FJson* Value = nullptr;
	return Object.IsValid() && Object->TryGetObjectField(Name, Value) ? *Value : nullptr;
}

FJson AsObject(const TSharedPtr<FJsonValue>& Value)
{
	return Value.IsValid() && Value->Type == EJson::Object ? Value->AsObject() : nullptr;
}

// "/Pkg/Dir/Name" -> "/Pkg/Dir/Name.Name"; full object paths and /Script/ paths are kept.
FString ObjectPath(const FString& Path)
{
	if (Path.StartsWith(TEXT("/Script/")) || Path.Contains(TEXT(".")))
	{
		return Path;
	}
	return Path + TEXT(".") + FPackageName::GetShortName(Path);
}

UObject* LoadAny(const FString& Path)
{
	return Path.IsEmpty() ? nullptr : StaticLoadObject(UObject::StaticClass(), nullptr, *ObjectPath(Path));
}

// A native class (/Script/Module.Class), a Blueprint (its generated class) or a generated class path.
UClass* LoadClassPath(const FString& Path)
{
	if (Path.IsEmpty())
	{
		return nullptr;
	}
	if (Path.StartsWith(TEXT("/Script/")))
	{
		return LoadObject<UClass>(nullptr, *Path);
	}
	const FString Full = ObjectPath(Path);
	if (UObject* Object = StaticLoadObject(UObject::StaticClass(), nullptr, *Full))
	{
		if (const UBlueprint* Blueprint = Cast<UBlueprint>(Object))
		{
			return Blueprint->GeneratedClass;
		}
		if (UClass* Class = Cast<UClass>(Object))
		{
			return Class;
		}
	}
	return LoadObject<UClass>(nullptr, *(Full + TEXT("_C")));
}

UScriptStruct* LoadStruct(const FString& Path)
{
	return LoadObject<UScriptStruct>(nullptr, *ObjectPath(Path));
}

// Type names: bool byte int int64 float double string text name vector vector2d rotator transform color,
// object:<class> class:<class> struct:<struct>, and a trailing [] for arrays.
bool ParsePinType(FString Type, FEdGraphPinType& Out, FReport& Report)
{
	Out = FEdGraphPinType();
	const FString Original = Type;
	if (Type.EndsWith(TEXT("[]")))
	{
		Out.ContainerType = EPinContainerType::Array;
		Type.LeftChopInline(2);
	}
	auto Struct = [&Out](UScriptStruct* Value)
	{
		Out.PinCategory = UEdGraphSchema_K2::PC_Struct;
		Out.PinSubCategoryObject = Value;
	};
	if (Type == TEXT("bool")) Out.PinCategory = UEdGraphSchema_K2::PC_Boolean;
	else if (Type == TEXT("byte")) Out.PinCategory = UEdGraphSchema_K2::PC_Byte;
	else if (Type == TEXT("int")) Out.PinCategory = UEdGraphSchema_K2::PC_Int;
	else if (Type == TEXT("int64")) Out.PinCategory = UEdGraphSchema_K2::PC_Int64;
	else if (Type == TEXT("float") || Type == TEXT("double"))
	{
		Out.PinCategory = UEdGraphSchema_K2::PC_Real;
		Out.PinSubCategory = UEdGraphSchema_K2::PC_Double;
	}
	else if (Type == TEXT("string")) Out.PinCategory = UEdGraphSchema_K2::PC_String;
	else if (Type == TEXT("text")) Out.PinCategory = UEdGraphSchema_K2::PC_Text;
	else if (Type == TEXT("name")) Out.PinCategory = UEdGraphSchema_K2::PC_Name;
	else if (Type == TEXT("vector")) Struct(TBaseStructure<FVector>::Get());
	else if (Type == TEXT("vector2d")) Struct(TBaseStructure<FVector2D>::Get());
	else if (Type == TEXT("rotator")) Struct(TBaseStructure<FRotator>::Get());
	else if (Type == TEXT("transform")) Struct(TBaseStructure<FTransform>::Get());
	else if (Type == TEXT("color")) Struct(TBaseStructure<FLinearColor>::Get());
	else if (Type.StartsWith(TEXT("object:")))
	{
		Out.PinCategory = UEdGraphSchema_K2::PC_Object;
		Out.PinSubCategoryObject = LoadClassPath(Type.Mid(7));
	}
	else if (Type.StartsWith(TEXT("class:")))
	{
		Out.PinCategory = UEdGraphSchema_K2::PC_Class;
		Out.PinSubCategoryObject = LoadClassPath(Type.Mid(6));
	}
	else if (Type.StartsWith(TEXT("struct:")))
	{
		Struct(LoadStruct(Type.Mid(7)));
	}
	else
	{
		Report.Error(FString::Printf(TEXT("unknown type '%s'"), *Original));
		return false;
	}
	const bool bNeedsObject = Out.PinCategory == UEdGraphSchema_K2::PC_Object
		|| Out.PinCategory == UEdGraphSchema_K2::PC_Class || Out.PinCategory == UEdGraphSchema_K2::PC_Struct;
	if (bNeedsObject && !Out.PinSubCategoryObject.IsValid())
	{
		Report.Error(FString::Printf(TEXT("type '%s': class or struct not found"), *Original));
		return false;
	}
	return true;
}

// Sets a property by name; dotted paths walk into struct members ("Font.Size"). Text takes plain strings,
// object and class properties take asset or class paths, everything else uses Unreal's text import format.
bool SetProperty(UObject* Object, const FString& Path, const FString& Value, FReport& Report)
{
	TArray<FString> Parts;
	Path.ParseIntoArray(Parts, TEXT("."));
	const UStruct* Struct = Object->GetClass();
	void* Container = Object;
	FProperty* Property = nullptr;
	for (int32 Index = 0; Index < Parts.Num(); ++Index)
	{
		Property = FindFProperty<FProperty>(Struct, FName(*Parts[Index]));
		if (!Property)
		{
			Report.Error(FString::Printf(TEXT("%s has no property '%s' (setting %s)"), *Struct->GetName(), *Parts[Index], *Path));
			return false;
		}
		if (Index + 1 < Parts.Num())
		{
			const FStructProperty* StructProperty = CastField<FStructProperty>(Property);
			if (!StructProperty)
			{
				Report.Error(FString::Printf(TEXT("'%s' in %s is not a struct"), *Parts[Index], *Path));
				return false;
			}
			Container = StructProperty->ContainerPtrToValuePtr<void>(Container);
			Struct = StructProperty->Struct;
		}
	}
	if (!Property)
	{
		Report.Error(TEXT("empty property path"));
		return false;
	}
	void* ValuePtr = Property->ContainerPtrToValuePtr<void>(Container);
	if (const FTextProperty* TextProperty = CastField<FTextProperty>(Property))
	{
		if (!Value.StartsWith(TEXT("NSLOCTEXT")) && !Value.StartsWith(TEXT("INVTEXT")) && !Value.StartsWith(TEXT("LOCTEXT")))
		{
			TextProperty->SetPropertyValue(ValuePtr, FText::AsCultureInvariant(Value));
			return true;
		}
	}
	else if (const FClassProperty* ClassProperty = CastField<FClassProperty>(Property))
	{
		UClass* Class = LoadClassPath(Value);
		if (!Value.IsEmpty() && (!Class || !Class->IsChildOf(ClassProperty->MetaClass)))
		{
			Report.Error(FString::Printf(TEXT("%s: '%s' is not a %s class"), *Path, *Value, *GetNameSafe(ClassProperty->MetaClass)));
			return false;
		}
		ClassProperty->SetObjectPropertyValue(ValuePtr, Class);
		return true;
	}
	else if (const FObjectPropertyBase* ObjectProperty = CastField<FObjectPropertyBase>(Property))
	{
		if (Value.StartsWith(TEXT("/")))
		{
			UObject* Loaded = LoadAny(Value);
			if (!Loaded || !Loaded->IsA(ObjectProperty->PropertyClass))
			{
				Report.Error(FString::Printf(TEXT("%s: '%s' not found or not a %s"), *Path, *Value, *GetNameSafe(ObjectProperty->PropertyClass)));
				return false;
			}
			ObjectProperty->SetObjectPropertyValue(ValuePtr, Loaded);
			return true;
		}
	}
	if (!Property->ImportText_Direct(*Value, ValuePtr, Object, PPF_None))
	{
		Report.Error(FString::Printf(TEXT("%s: can't import '%s' into a %s"), *Path, *Value, *Property->GetCPPType()));
		return false;
	}
	return true;
}

void ApplyProps(UObject* Object, const FJson& Props, FReport& Report)
{
	if (!Object || !Props.IsValid())
	{
		return;
	}
	for (const TPair<FString, TSharedPtr<FJsonValue>>& Pair : Props->Values)
	{
		SetProperty(Object, Pair.Key, ValueToString(Pair.Value), Report);
	}
}

// Appends an object to a TArray<TObjectPtr<..>> property of a UObject or of a struct inside one.
bool AppendObject(const UStruct* Struct, void* Container, const TCHAR* ArrayName, UObject* Value, FReport& Report)
{
	const FArrayProperty* Array = FindFProperty<FArrayProperty>(Struct, ArrayName);
	const FObjectPropertyBase* Inner = Array ? CastField<FObjectPropertyBase>(Array->Inner) : nullptr;
	if (!Inner)
	{
		Report.Error(FString::Printf(TEXT("%s has no object array '%s'"), *Struct->GetName(), ArrayName));
		return false;
	}
	FScriptArrayHelper Helper(Array, Array->ContainerPtrToValuePtr<void>(Container));
	const int32 Index = Helper.AddValue();
	Inner->SetObjectPropertyValue(Helper.GetRawPtr(Index), Value);
	return true;
}

// An instanced sub-object such as an input trigger or modifier: {"class": .., "props": {..}}.
UObject* MakeInstanced(UObject* Outer, const FJson& Spec, const UClass* Base, FReport& Report)
{
	const FString ClassPath = StringField(Spec, TEXT("class"));
	UClass* Class = LoadClassPath(ClassPath);
	if (!Class || !Class->IsChildOf(Base) || Class->HasAnyClassFlags(CLASS_Abstract))
	{
		Report.Error(FString::Printf(TEXT("'%s' is not a concrete %s class"), *ClassPath, *Base->GetName()));
		return nullptr;
	}
	UObject* Object = NewObject<UObject>(Outer, Class, NAME_None, RF_Public | RF_Transactional);
	ApplyProps(Object, ObjectField(Spec, TEXT("props")), Report);
	return Object;
}

UPackage* NewAssetPackage(const FString& PackagePath, FReport& Report)
{
	if (!FPackageName::IsValidLongPackageName(PackagePath))
	{
		Report.Error(FString::Printf(TEXT("'%s' is not a valid package path"), *PackagePath));
		return nullptr;
	}
	const FString AssetName = FPackageName::GetShortName(PackagePath);
	if (FPackageName::DoesPackageExist(PackagePath) || FindObject<UObject>(nullptr, *ObjectPath(PackagePath)))
	{
		Report.Error(FString::Printf(TEXT("%s already exists; delete it first (ForceDeleteAssets)"), *PackagePath));
		return nullptr;
	}
	UPackage* Package = CreatePackage(*PackagePath);
	Package->FullyLoad();
	return Package;
}

void Created(UObject* Asset)
{
	FAssetRegistryModule::AssetCreated(Asset);
	Asset->MarkPackageDirty();
}

// --- Cooked, user-defined structs ---------------------------------------------------------------
// Persist explicit GUIDs in the source spec. Random GUIDs on each authoring run would make a
// SaveGame's member tags stop matching after rebuilding a mod.
void BuildStruct(const FJson& Spec, FReport& Report)
{
	const FString Path = StringField(Spec, TEXT("path"));
	FGuid StructGuid;
	if (!FGuid::Parse(StringField(Spec, TEXT("guid")), StructGuid) || !StructGuid.IsValid())
	{
		Report.Error(TEXT("struct requires a stable, nonzero 'guid'"));
		return;
	}
	TArray<FStructVariableDescription> Members;
	TSet<FName> Names;
	TSet<FGuid> Guids;
	for (const TSharedPtr<FJsonValue>& Value : ArrayField(Spec, TEXT("fields")))
	{
		const FJson Field = AsObject(Value);
		FStructVariableDescription Member;
		Member.FriendlyName = StringField(Field, TEXT("name"));
		const FName Name(*Member.FriendlyName);
		FEdGraphPinType Type;
		if (Name.IsNone() || Names.Contains(Name)
			|| !FGuid::Parse(StringField(Field, TEXT("guid")), Member.VarGuid)
			|| !Member.VarGuid.IsValid() || Guids.Contains(Member.VarGuid))
		{
			Report.Error(TEXT("struct fields require unique names and stable, nonzero GUIDs"));
			return;
		}
		if (!ParsePinType(StringField(Field, TEXT("type")), Type, Report) || !Member.SetPinType(Type))
		{
			Report.Error(FString::Printf(TEXT("invalid type for struct field '%s'"), *Member.FriendlyName));
			return;
		}
		// Keep the name independent of member ordering, with the standard UDS GUID suffix.
		Member.VarName = FName(*(Member.FriendlyName + TEXT("_0_") + Member.VarGuid.ToString(EGuidFormats::Digits)));
		Member.DefaultValue = StringField(Field, TEXT("default"));
		Member.CurrentDefaultValue = Member.DefaultValue;
		Member.bEnableSaveGame = true;
		Names.Add(Name);
		Guids.Add(Member.VarGuid);
		Members.Add(MoveTemp(Member));
	}
	if (Members.IsEmpty())
	{
		Report.Error(TEXT("struct requires at least one field"));
		return;
	}
	UPackage* Package = NewAssetPackage(Path, Report);
	if (!Package) return;
	UUserDefinedStruct* Struct = FStructureEditorUtils::CreateUserDefinedStruct(
		Package, FName(*FPackageName::GetShortName(Path)), RF_Public | RF_Standalone | RF_Transactional);
	if (!Struct)
	{
		Report.Error(TEXT("could not create user-defined struct"));
		return;
	}
	Struct->Guid = StructGuid;
	FStructureEditorUtils::GetVarDesc(Struct) = MoveTemp(Members);
	FStructureEditorUtils::OnStructureChanged(Struct);
	if (Struct->Status != UDSS_UpToDate)
	{
		Report.Error(FString::Printf(TEXT("struct compilation failed: %s"), *Struct->ErrorMessage));
		return;
	}
	Created(Struct);
}

// --- Input assets ---------------------------------------------------------------------------------

void AddTriggersAndModifiers(UObject* Outer, const FJson& Spec, const UStruct* Struct, void* Container, FReport& Report)
{
	for (const TSharedPtr<FJsonValue>& Value : ArrayField(Spec, TEXT("triggers")))
	{
		if (UObject* Trigger = MakeInstanced(Outer, AsObject(Value), UInputTrigger::StaticClass(), Report))
		{
			AppendObject(Struct, Container, TEXT("Triggers"), Trigger, Report);
		}
	}
	for (const TSharedPtr<FJsonValue>& Value : ArrayField(Spec, TEXT("modifiers")))
	{
		if (UObject* Modifier = MakeInstanced(Outer, AsObject(Value), UInputModifier::StaticClass(), Report))
		{
			AppendObject(Struct, Container, TEXT("Modifiers"), Modifier, Report);
		}
	}
}

void BuildInputAction(const FJson& Spec, FReport& Report)
{
	const FString Path = StringField(Spec, TEXT("path"));
	UPackage* Package = NewAssetPackage(Path, Report);
	if (!Package)
	{
		return;
	}
	UInputAction* Action = NewObject<UInputAction>(Package, FName(*FPackageName::GetShortName(Path)), RF_Public | RF_Standalone | RF_Transactional);
	SetProperty(Action, TEXT("ValueType"), StringField(Spec, TEXT("value_type"), TEXT("Boolean")), Report);
	bool bConsume = true;
	if (Spec->TryGetBoolField(TEXT("consume_input"), bConsume))
	{
		SetProperty(Action, TEXT("bConsumeInput"), bConsume ? TEXT("true") : TEXT("false"), Report);
	}
	AddTriggersAndModifiers(Action, Spec, UInputAction::StaticClass(), Action, Report);
	ApplyProps(Action, ObjectField(Spec, TEXT("props")), Report);
	Created(Action);
}

void BuildMappingContext(const FJson& Spec, FReport& Report)
{
	const FString Path = StringField(Spec, TEXT("path"));
	UPackage* Package = NewAssetPackage(Path, Report);
	if (!Package)
	{
		return;
	}
	UInputMappingContext* Context = NewObject<UInputMappingContext>(Package, FName(*FPackageName::GetShortName(Path)), RF_Public | RF_Standalone | RF_Transactional);
	for (const TSharedPtr<FJsonValue>& Value : ArrayField(Spec, TEXT("mappings")))
	{
		const FJson Mapping = AsObject(Value);
		const FString ActionPath = StringField(Mapping, TEXT("action"));
		const UInputAction* Action = Cast<UInputAction>(LoadAny(ActionPath));
		const FKey Key(FName(*StringField(Mapping, TEXT("key"))));
		if (!Action || !Key.IsValid())
		{
			Report.Error(FString::Printf(TEXT("mapping %s -> '%s': action or key not found"), *ActionPath, *StringField(Mapping, TEXT("key"))));
			continue;
		}
		FEnhancedActionKeyMapping& KeyMapping = Context->MapKey(Action, Key);
		AddTriggersAndModifiers(Context, Mapping, FEnhancedActionKeyMapping::StaticStruct(), &KeyMapping, Report);
	}
	ApplyProps(Context, ObjectField(Spec, TEXT("props")), Report);
	Created(Context);
}

