"""Native named presets: one transactional library with value-only layout snapshots."""
from graph import Graph, variable as v, KML, KSL, GS
from runtime_store import call, branch, combine, STR, ARRAY


def library_specs(root, layout, entry_type, struct, save_variables, store_spec, arr, unpack):
    preset=root+'ST_DenPresetValue'
    library=root+'BP_DenPresetLibrary'
    yield '08_ST_DenPresetValue',struct(preset,[v('Name','string'),v('GameVersion','string'),v('Entries','struct:'+entry_type+'[]')])
    yield '09_BP_DenPresetLibrary',dict(kind='blueprint',path=library,parent='/Script/Engine.SaveGame',
                                      variables=save_variables(preset,'preset-library'))
    yield '10_BP_DenPresetStore',store_spec(root,library,'BP_DenPresetStore','AsBP Den Preset Library','Library')

    def normalize():
        g=Graph()
        left=call(g,'left',STR+'Trim',{'SourceString':'entry.Name'})
        trimmed=call(g,'trimmed',STR+'TrimTrailing',{'SourceString':left})
        length=call(g,'length',STR+'Len',{'S':trimmed})
        low=call(g,'low',KML+':Greater_IntInt',{'A':length},B=0)
        high=call(g,'high',KML+':LessEqual_IntInt',{'A':length},B=40)
        branch(g,'size',combine(g,'sizeok',[low,high]))
        g.get('i','local:Cursor')
        within=call(g,'within',KML+':Less_IntInt',{'A':'i.Cursor','B':length})
        branch(g,'loop',within)
        char=call(g,'char',STR+'GetCharacterAsNumber',{'SourceString':trimmed,'Index':'i.Cursor'})
        printable=call(g,'printable',KML+':GreaterEqual_IntInt',{'A':char},B=32)
        notdel=call(g,'notdel',KML+':NotEqual_IntInt',{'A':char},B=127)
        branch(g,'allowed',combine(g,'charok',[printable,notdel]))
        nxt=call(g,'next',KML+':Add_IntInt',{'A':'i.Cursor'},B=1)
        g.set('advance','local:Cursor')
        g.wire((nxt,'advance.Cursor'))
        g.set('yes','local:NameValid','true')
        g.get('yesout','local:NameValid')
        g.wire((trimmed,'result.CleanName'),('yesout.NameValid','result.Valid'))
        g.chain('entry','size','loop','allowed','advance','loop')
        g.chain('size.else','result')
        g.chain('allowed.else','result')
        g.chain('loop.else','yes','result')
        return g.function('NormalizeName',inputs=[v('Name','string')],outputs=[v('CleanName','string'),v('Valid','bool')],
                          locals=[v('Cursor','int','0'),v('NameValid','bool','false')])

    def open_library():
        g=Graph()
        g.get('librarykey','LibraryKey');g.call('load','self:LoadLibrary',Draft='false',BeforeRevision=0);g.wire(('librarykey.LibraryKey','load.Key'))
        g.set('status','local:ResultStatus')
        g.wire(('load.Status','status.ResultStatus'))
        missing=call(g,'missing',KML+':EqualEqual_IntInt',{'A':'load.Status'},B=0)
        branch(g,'new',missing)
        call(g,'create',GS+':CreateSaveGameObject',SaveGameClass=library)
        g.node('cast','cast',**{'class':library})
        g.wire(('create.ReturnValue','cast.Object'))
        g.set('created','local:ResultLibrary')
        g.wire(('cast.AsBP Den Preset Library','created.ResultLibrary'))
        g.set('loaded','local:ResultLibrary')
        g.wire(('load.Document','loaded.ResultLibrary'))
        g.set('fail','local:ResultStatus','7')
        g.get('out','local:ResultLibrary')
        g.get('statusout','local:ResultStatus')
        g.wire(('out.ResultLibrary','result.Library'),('statusout.ResultStatus','result.Status'))
        g.chain('entry','load','status','new','create','cast','created','result')
        g.chain('new.else','loaded','result')
        g.chain('cast.CastFailed','fail','result')
        return g.function('OpenLibrary',outputs=[v('Library','object:'+library),v('Status','int')],
                          locals=[v('ResultLibrary','object:'+library),v('ResultStatus','int','0')])

    def find():
        g=Graph()
        valid=call(g,'valid',KSL+':IsValid',{'Object':'entry.Library'})
        branch(g,'guard',valid)
        g.get('rows',library+':Entries')
        g.wire(('entry.Library','rows.self'))
        arr(g,'length','Length','rows.Entries')
        g.get('i','local:Cursor')
        within=call(g,'within',KML+':Less_IntInt',{'A':'i.Cursor','B':'length.ReturnValue'})
        branch(g,'loop',within)
        arr(g,'row','Get','rows.Entries')
        g.wire(('i.Cursor','row.Index'))
        unpack(g,'fields',preset,'row.Item')
        same=call(g,'same',STR+'EqualEqual_StriStri',{'A':'entry.Name','B':'fields.Name'})
        branch(g,'match',same)
        g.set('found','local:FoundIndex')
        g.wire(('i.Cursor','found.FoundIndex'))
        nxt=call(g,'next',KML+':Add_IntInt',{'A':'i.Cursor'},B=1)
        g.set('advance','local:Cursor')
        g.wire((nxt,'advance.Cursor'))
        g.get('out','local:FoundIndex')
        g.wire(('out.FoundIndex','result.Index'))
        g.chain('entry','guard','loop','match','found','result')
        g.chain('guard.else','result')
        g.chain('loop.else','result')
        g.chain('match.else','advance','loop')
        return g.function('FindPreset',inputs=[v('Library','object:'+library),v('Name','string')],outputs=[v('Index','int')],
                          locals=[v('Cursor','int','0'),v('FoundIndex','int','-1')])

    def setup(g):
        g.call('name','self:NormalizeName')
        g.wire(('entry.Name','name.Name'))
        branch(g,'validname','name.Valid')
        g.call('open','self:OpenLibrary')
        g.set('status','local:ResultStatus')
        g.wire(('open.Status','status.ResultStatus'))
        healthy=call(g,'healthy',KML+':LessEqual_IntInt',{'A':'open.Status'},B=2)
        branch(g,'usable',healthy)
        g.call('find','self:FindPreset')
        g.wire(('open.Library','find.Library'),('name.CleanName','find.Name'))
        g.get('rows',library+':Entries')
        g.wire(('open.Library','rows.self'))
        g.get('statusout','local:ResultStatus')
        g.wire(('statusout.ResultStatus','result.Status'))
        g.chain('entry','name','validname','open','status','usable','find')
        g.chain('validname.else','result')
        g.chain('usable.else','result')

    def save():
        g=Graph()
        setup(g)
        valid=call(g,'docvalid',KSL+':IsValid',{'Object':'entry.Document'})
        branch(g,'hasdoc',valid)
        g.get('schema',layout+':SchemaVersion')
        g.wire(('entry.Document','schema.self'))
        same=call(g,'schemaok',KML+':EqualEqual_IntInt',{'A':'schema.SchemaVersion'},B=1)
        branch(g,'current',same)
        g.node('preset','make_struct',struct=preset)
        for field in ['Entries','GameVersion']:
            g.get('source'+field,layout+':'+field)
            g.wire(('entry.Document','source'+field+'.self'),('source'+field+'.'+field,'preset.'+field))
        g.wire(('name.CleanName','preset.Name'))
        found=call(g,'found',KML+':GreaterEqual_IntInt',{'A':'find.Index'},B=0)
        branch(g,'replace',found)
        arr(g,'set','Set','rows.Entries',bSizeToFit='false')
        arr(g,'add','Add','rows.Entries')
        g.wire(('find.Index','set.Index'),('preset.ST_DenPresetValue','set.Item'),('preset.ST_DenPresetValue','add.NewItem'))
        g.get('librarykey','LibraryKey');g.call('save','self:SaveLibrary',Draft='false',BaseRevision=0,BaseID='');g.wire(('librarykey.LibraryKey','save.Key'))
        g.wire(('open.Library','save.Document'))
        g.set('savedstatus','local:ResultStatus')
        g.wire(('save.Status','savedstatus.ResultStatus'),('name.CleanName','result.CleanName'))
        g.set('bad','local:ResultStatus','7')
        g.chain('find','hasdoc','current','replace','set','save','savedstatus','result')
        g.chain('replace.else','add','save')
        g.chain('hasdoc.else','bad','result')
        g.chain('current.else','bad')
        return g.function('SavePreset',inputs=[v('Name','string'),v('Document','object:'+layout)],
                          outputs=[v('Status','int'),v('CleanName','string')],locals=[v('ResultStatus','int','7')])

    def load():
        g=Graph()
        setup(g)
        found=call(g,'found',KML+':GreaterEqual_IntInt',{'A':'find.Index'},B=0)
        branch(g,'exists',found)
        arr(g,'row','Get','rows.Entries')
        g.wire(('find.Index','row.Index'))
        unpack(g,'fields',preset,'row.Item')
        call(g,'create',GS+':CreateSaveGameObject',SaveGameClass=layout)
        g.node('cast','cast',**{'class':layout})
        g.wire(('create.ReturnValue','cast.Object'))
        for name,field in [('Entries','Entries'),('GameVersion','GameVersion'),('DisplayName','Name')]:
            g.set('set'+name,layout+':'+name)
            g.wire(('cast.AsBP Den Layout Save','set'+name+'.self'),('fields.'+field,'set'+name+'.'+name))
        g.set('scope',layout+':Scope','preset')
        g.wire(('cast.AsBP Den Layout Save','scope.self'))
        g.set('copy','local:ResultDocument')
        g.wire(('cast.AsBP Den Layout Save','copy.ResultDocument'))
        g.get('out','local:ResultDocument')
        g.wire(('out.ResultDocument','result.Document'))
        g.set('missing','local:ResultStatus','0')
        g.set('failed','local:ResultStatus','7')
        g.chain('find','exists','create','cast','setEntries','setGameVersion','setDisplayName','scope','copy','result')
        g.chain('exists.else','missing','result')
        g.chain('cast.CastFailed','failed','result')
        return g.function('LoadPreset',inputs=[v('Name','string')],outputs=[v('Document','object:'+layout),v('Status','int')],
                          locals=[v('ResultDocument','object:'+layout),v('ResultStatus','int','7')])

    def delete():
        g=Graph()
        setup(g)
        found=call(g,'found',KML+':GreaterEqual_IntInt',{'A':'find.Index'},B=0)
        branch(g,'exists',found)
        arr(g,'remove','Remove','rows.Entries')
        g.wire(('find.Index','remove.IndexToRemove'))
        g.get('librarykey','LibraryKey');g.call('save','self:SaveLibrary',Draft='false',BaseRevision=0,BaseID='');g.wire(('librarykey.LibraryKey','save.Key'))
        g.wire(('open.Library','save.Document'))
        g.set('savedstatus','local:ResultStatus')
        g.wire(('save.Status','savedstatus.ResultStatus'))
        g.set('missing','local:ResultStatus','1')
        g.chain('find','exists','remove','save','savedstatus','result')
        g.chain('exists.else','missing','result')
        return g.function('DeletePreset',inputs=[v('Name','string')],outputs=[v('Status','int')],locals=[v('ResultStatus','int','7')])

    def listing():
        g=Graph()
        g.call('open','self:OpenLibrary')
        healthy=call(g,'healthy',KML+':LessEqual_IntInt',{'A':'open.Status'},B=2)
        branch(g,'usable',healthy)
        g.get('rows',library+':Entries')
        g.wire(('open.Library','rows.self'))
        arr(g,'length','Length','rows.Entries')
        g.get('i','local:Cursor')
        within=call(g,'within',KML+':Less_IntInt',{'A':'i.Cursor','B':'length.ReturnValue'})
        branch(g,'loop',within)
        arr(g,'row','Get','rows.Entries')
        g.wire(('i.Cursor','row.Index'))
        unpack(g,'fields',preset,'row.Item')
        g.get('names','local:ResultNames')
        arr(g,'append','Add','names.ResultNames')
        g.wire(('fields.Name','append.NewItem'))
        nxt=call(g,'next',KML+':Add_IntInt',{'A':'i.Cursor'},B=1)
        g.set('advance','local:Cursor')
        g.wire((nxt,'advance.Cursor'))
        call(g,'sort',ARRAY+'SortStringArray',{'TargetArray':'names.ResultNames'},bStableSort='true',SortOrder='Ascending')
        g.wire(('names.ResultNames','result.Names'),('open.Status','result.Status'))
        g.chain('entry','open','usable','loop','append','advance','loop')
        g.chain('loop.else','sort','result')
        g.chain('usable.else','result')
        return g.function('ListPresets',outputs=[v('Names','string[]'),v('Status','int')],locals=[v('ResultNames','string[]'),v('Cursor','int','0')])

    yield '11_BP_DenPresets',dict(kind='blueprint',path=root+'BP_DenPresets',parent=root+'BP_DenPresetStore',
                                variables=[v('LibraryKey','string','presets')],functions=[normalize(),open_library(),find(),save(),load(),delete(),listing()])
